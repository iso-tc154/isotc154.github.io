import fs from 'node:fs'
import path from 'node:path'
import { committee } from '../src/data/committee.ts'

const ROOT = path.resolve(import.meta.dirname, '..')
const SRC = path.join(ROOT, '_data/resolutions')
const STAGE = path.join(ROOT, '_data/resolutions-edoxen')
const COMMITTEE_STAGE = path.join(ROOT, '_data/committee-edoxen')

const SUBDIRS = ['plenary', '7372ma', 'ballots']

// Start clean — staging dir is .gitignored and ephemeral.
if (fs.existsSync(STAGE)) {
  fs.rmSync(STAGE, { recursive: true, force: true })
}
fs.mkdirSync(STAGE, { recursive: true })

let total = 0
for (const sub of SUBDIRS) {
  const srcDir = path.join(SRC, sub)
  if (!fs.existsSync(srcDir)) {
    console.warn(`[prepare-edoxen-data] skip ${sub}/ (missing)`)
    continue
  }
  const yamlFiles = fs.readdirSync(srcDir).filter((f) => f.endsWith('.yaml'))
  for (const f of yamlFiles) {
    // Hard-link when possible (same filesystem, fast), fall back to copy.
    const src = path.join(srcDir, f)
    const dst = path.join(STAGE, f)
    try {
      fs.linkSync(src, dst)
    } catch {
      fs.copyFileSync(src, dst)
    }
  }
  console.log(`[prepare-edoxen-data] ${sub}/ → ${yamlFiles.length} YAML files (flat)`)
  total += yamlFiles.length
}
console.log(`[prepare-edoxen-data] staged ${total} YAML files in ${path.relative(ROOT, STAGE)}/`)


// Committee register for @edoxen/browser: generated from src/data/committee.ts
// (identity facts) plus the counts the data pipeline just wrote to meta.json —
// one source of truth, derived output (the same principle as image masters).
function syncCommittee() {
  fs.mkdirSync(COMMITTEE_STAGE, { recursive: true })
  const metaPath = path.join(ROOT, 'public/data/meta.json')
  if (!fs.existsSync(metaPath)) {
    // CI's validate job stages edoxen data before build-data runs; the
    // committee register (which needs meta counts) is only consumed by
    // the astro build, which always follows build-data. Skip here.
    console.log('[prepare-edoxen-data] meta.json not built yet — committee.yaml generation skipped')
    return
  }
  const c = JSON.parse(fs.readFileSync(metaPath, 'utf8')).counts ?? {}
  const doc = {
    identifier: [{ prefix: 'ISO/TC 154', number: '154' }],
    meeting_refs: [],
    urn: 'urn:iso:tc154:series:plenary',
    name: [{ spelling: 'eng', value: committee.name }],
    description: [{ spelling: 'eng', value: committee.scope }],
    extensions: [{
      attributes: [
        { key: 'tagline', type: 'string', value: committee.tagline },
        { key: 'established_year', type: 'integer', intValue: committee.established },
        { key: 'published_standards', type: 'integer', intValue: c.publishedStandards ?? 0 },
        { key: 'participating_members', type: 'integer', intValue: c.participatingMembers ?? 0 },
        { key: 'observing_members', type: 'integer', intValue: c.observingMembers ?? 0 },
        { key: 'iso', type: 'string', value: committee.links.iso },
        { key: 'iso_committee', type: 'string', value: committee.links.isoCommittee },
        { key: 'linkedin', type: 'string', value: committee.links.linkedin },
        { key: 'github', type: 'string', value: committee.links.github },
      ],
    }],
    hosts: [{ role: 'secretariat', ref: 'sac' }],
    contact: { name: [{ spelling: 'eng', value: committee.chair }] },
  }
  const yaml = renderYaml(doc)
  const out = path.join(COMMITTEE_STAGE, 'committee.yaml')
  fs.writeFileSync(out, yaml)
  console.log(`[prepare-edoxen-data] committee.yaml generated (P:${c.participatingMembers} O:${c.observingMembers} published:${c.publishedStandards})`)
}

// Minimal targeted emitter — keeps the generated file's shape stable and
// diff-friendly (key order as above, localized arrays inline).
function renderYaml(doc) {
  const L = []
  L.push('# Committee register for @edoxen/browser: drives the site-style footer')
  L.push('# (brand, facts, explore, links) on the /decisions/ pages.')
  L.push('# GENERATED by scripts/prepare-edoxen-data.mjs from src/data/committee.ts')
  L.push('# + public/data/meta.json — do not edit by hand.')
  L.push('identifier:')
  L.push("  - prefix: ISO/TC 154")
  L.push("    number: '154'")
  L.push('meeting_refs: []')
  L.push('urn: urn:iso:tc154:series:plenary')
  L.push('name:')
  L.push(`  - spelling: eng`)
  L.push(`    value: ${doc.name[0].value}`)
  L.push('description:')
  L.push('  - spelling: eng')
  L.push(`    value: >-
      ${doc.description[0].value}`)
  L.push('extensions:')
  L.push('  - attributes:')
  for (const a of doc.extensions[0].attributes) {
    if (a.intValue !== undefined) {
      L.push(`      - key: ${a.key}`)
      L.push(`        type: integer`)
      L.push(`        intValue: ${a.intValue}`)
    } else {
      L.push(`      - key: ${a.key}`)
      L.push(`        type: string`)
      L.push(`        value: ${a.value}`)
    }
  }
  L.push('hosts:')
  L.push('  - role: secretariat')
  L.push('    ref: sac')
  L.push('contact:')
  L.push('  name:')
  L.push('    - spelling: eng')
  L.push(`      value: ${doc.contact.name[0].value}`)
  return L.join('\n') + '\n'
}

syncCommittee()
